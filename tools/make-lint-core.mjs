// Builds src/assets/lint-core.js (browser) from tools/lint-ia.mjs (vendored copy of vread-revenue-lab/content/lint-ia.mjs).
// The rules and analyse() are copied verbatim: the browser checker gives the same score as the CLI.
import fs from 'node:fs';
export function makeLintCore(src) {
  const a = src.indexOf('const RULES = [');
  const b = src.indexOf('// CLI\n');
  if (a < 0 || b < 0) throw new Error('lint-ia.mjs layout changed: markers not found');
  let core = src.slice(a, src.lastIndexOf('// ----', b));
  const verdict = src.match(/const verdict = \(r\) => \{[\s\S]*?\n\};/);
  if (!verdict) throw new Error('verdict() not found');
  return `/*! lint-core.js: rules and scoring of lint-ia.mjs (READ FRANCE SAS), generated by tools/make-lint-core.mjs. Runs in the browser only: the text is never sent. */
window.LintIA = (function () {
${core}
${verdict[0]}
return { analyse: analyse, verdict: verdict, RULES: RULES, COMPILED: COMPILED, TRIAD: TRIAD };
})();
`;
}
if (process.argv[1] && process.argv[1].endsWith('make-lint-core.mjs')) {
  fs.writeFileSync(new URL('../src/assets/lint-core.js', import.meta.url), makeLintCore(fs.readFileSync(new URL('./lint-ia.mjs', import.meta.url), 'utf8')));
  console.log('lint-core.js written');
}
